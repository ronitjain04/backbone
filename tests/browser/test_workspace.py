from playwright.sync_api import expect
from tests.browser.support.server import TEACHER_TOKEN


def start(page,base):
    page.goto(base+'/practice.html')
    page.get_by_label('Display name (optional)').fill('Browser student')
    page.get_by_role('button',name='Try as a student ↗',exact=True).click()
    expect(page.get_by_role('button',name='Check my work ↗',exact=True)).to_be_visible()


def test_student_correction_transfer_teacher_evidence_and_replay(page,live_server):
    page.set_viewport_size({'width':1440,'height':1000});start(page,live_server)
    page.get_by_role('button',name='Total capacity',exact=True).click()
    expect(page.get_by_role('heading',name='Total capacity',exact=True)).to_be_visible()
    page.get_by_label('Final answer',exact=True).fill('2048 bits')
    page.locator('#practice-work').fill('2048 bits = 2048 bytes')
    page.get_by_role('button',name='Check my work ↗',exact=True).click()
    expect(page.get_by_role('heading',name='Bits and bytes represent different quantities',exact=True)).to_be_visible()
    page.get_by_role('button',name='I’m stuck',exact=True).click()
    expect(page.locator('#practice-feedback')).to_contain_text('Hint 1 of 3',ignore_case=True)
    page.get_by_role('button',name='Explore a memory diagram',exact=True).click()
    expect(page.locator('#practice-visual')).to_contain_text('2048 bits = 2048 bytes')
    page.get_by_role('button',name='Show the next relationship',exact=True).click()
    expect(page.locator('#practice-visual')).to_contain_text('STEP 2 OF 3')
    page.reload()
    expect(page.get_by_label('Final answer',exact=True)).to_have_value('2048 bits')
    page.get_by_role('button',name='Resume memory explanation',exact=True).click()
    expect(page.locator('#practice-visual')).to_contain_text('STEP 2 OF 3')
    page.get_by_label('Final answer',exact=True).fill('2 KiB');page.locator('#practice-work').fill('')
    page.get_by_role('button',name='Check my work ↗',exact=True).click()
    expect(page.locator('#practice-outcome')).to_have_text('Corrected with help')
    page.get_by_role('button',name='Try the follow-up ↗',exact=True).click()
    expect(page.locator('#exercise-topic')).to_contain_text('Follow-up')
    page.get_by_label('Final answer',exact=True).fill('1024 bytes')
    page.get_by_role('button',name='Check my work ↗',exact=True).click()
    expect(page.locator('#practice-outcome')).to_have_text('Solved independently')
    teacher=page.context.new_page();teacher.goto(live_server+'/teacher.html')
    teacher.get_by_label('Teacher access token',exact=True).fill(TEACHER_TOKEN)
    teacher.get_by_role('button',name='Open classroom ↗',exact=True).click()
    row=teacher.get_by_role('row').filter(has_text='Browser student')
    expect(row).to_contain_text('Original: Corrected with help')
    expect(row).to_contain_text('Follow-up: Solved independently')
    expect(row).to_contain_text('1 hints delivered')
    row.get_by_role('button',name='Inspect work',exact=True).click()
    teacher.get_by_role('button',name='Replay this moment',exact=True).click()
    expect(teacher.get_by_role('slider',name='Replay timeline')).to_be_visible()
    teacher.get_by_role('slider',name='Replay timeline').press('Home')
    teacher.get_by_role('button',name='Play',exact=True).click()
    teacher.get_by_role('button',name='Pause',exact=True).click()
    teacher.get_by_role('button',name='Next moment',exact=True).click()
    expect(teacher.locator('#teacher-replay')).to_contain_text('Supported mistake')
    teacher.get_by_role('button',name='Lock classroom',exact=True).click()
    expect(teacher.get_by_role('button',name='Open classroom ↗',exact=True)).to_be_visible()
    expect(teacher.locator('#teacher-students')).to_be_empty();teacher.close()


def test_mobile_workspace_and_teacher_do_not_widen_page(page,live_server):
    page.set_viewport_size({'width':390,'height':844});start(page,live_server)
    page.get_by_label('Choose an exercise',exact=True).select_option('mem-03')
    page.get_by_role('button',name='Explore a memory diagram',exact=True).click()
    expect(page.locator('#practice-visual')).to_contain_text('STEP 1 OF 3')
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.goto(live_server+'/teacher.html')
    page.get_by_label('Teacher access token',exact=True).fill(TEACHER_TOKEN)
    page.get_by_role('button',name='Open classroom ↗',exact=True).click()
    expect(page.get_by_role('table')).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    assert page.locator('.classroom-scroll').evaluate('(e)=>e.scrollWidth>e.clientWidth')
